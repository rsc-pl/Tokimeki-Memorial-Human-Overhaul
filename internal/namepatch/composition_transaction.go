package namepatch

// composition byte-ownership audit is a closed, RAM-only composition and byte-diff safety audit of the
// existing N10 Phase-2 stages.  It has no filesystem, disc or installer side effects.  Runtime memory ownership and parser safety are NOT proved.

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"sort"
)

// N10OfflineTransaction is an explicitly revision-pinned input snapshot. The
// original map contains the authenticated retail EXE and three overlays; the
// staged EXE is a COPY with the existing English renderer and short names.
// Callers MUST supply the exact staged digest, rather than accepting unknown
// parallel changes to translation-generated bytes.
type N10OfflineTransaction struct {
	Originals    map[string][]byte
	StagedEXE    []byte
	StagedEXESHA [32]byte
	CurrentShort []string
	TargetShort  []string
	TargetFull   []string
	GEKOG2Policy string
}

type N10DiffRange struct {
	Start        int `json:"start"`
	EndExclusive int `json:"end_exclusive"`
}
type N10ImageDiff struct {
	Name          string         `json:"name"`
	InputSHA256   string         `json:"input_sha256"`
	OutputSHA256  string         `json:"output_sha256"`
	ChangedBytes  int            `json:"changed_bytes"`
	AllowedRanges []N10DiffRange `json:"allowed_ranges"`
}
type N10OfflineTransactionReport struct {
	ShortBytes      int                   `json:"short_bytes"`
	FullFirstBytes  int                   `json:"full_first_bytes"`
	FullSecondBytes int                   `json:"full_second_bytes"`
	RewrittenA      int                   `json:"rewritten_a"`
	RewrittenB      int                   `json:"rewritten_b"`
	AliasSources    int                   `json:"alias_sources"`
	GEKOG2Policy    string                `json:"geko_g2_policy"`
	ParserCalls     int                   `json:"parser_calls"`
	ParserGuarded   bool                  `json:"parser_guarded"`
	Presentation    N10PresentationReport `json:"presentation"`
	Diffs           []N10ImageDiff        `json:"diffs"`
	RuntimeVerified bool                  `json:"runtime_verified"`
	SafeToPatch     bool                  `json:"safe_to_patch"`
}

func n10AllowRange(m map[string][]N10DiffRange, name string, a, b int) {
	m[name] = append(m[name], N10DiffRange{Start: a, EndExclusive: b})
}

// n10Phase2AllowedDiffs is an independent maximum diff surface. If future
// stages change code/data elsewhere, even a syntactically valid transformation
// will fail until an engineer explicitly reviews the new surface.
func n10Phase2AllowedDiffs() map[string][]N10DiffRange {
	m := make(map[string][]N10DiffRange)
	n10AllowRange(m, EXE, 0xb278, 0xb278+132)                   // renderer-tail short strings only
	n10AllowRange(m, EXE, N10FullPoolStart, N10Phase2SpareEnd)  // split full data, tables, A/B/G2
	n10AllowRange(m, EXE, PointerTable, PointerTable+Entries*4) // short pointers
	for _, p := range verifiedFixedDirectEXE {
		n10AllowRange(m, EXE, p.UpperOffset, p.UpperOffset+4)
		n10AllowRange(m, EXE, p.LowerOffset, p.LowerOffset+4)
	}
	for _, a := range []int{0x3ff94, 0x40068} {
		n10AllowRange(m, EXE, a, a+4)
	}
	for name, pairs := range n10Phase2ASites {
		for _, p := range pairs {
			base := n10Phase2Base[name]
			n10AllowRange(m, name, int(p[0]-base), int(p[0]-base)+4)
			n10AllowRange(m, name, int(p[1]-base), int(p[1]-base)+4)
		}
	}
	for name, pairs := range n10Phase2BSites {
		for _, p := range pairs {
			base := n10Phase2Base[name]
			n10AllowRange(m, name, int(p[0]-base), int(p[0]-base)+4)
			n10AllowRange(m, name, int(p[1]-base), int(p[1]-base)+4)
		}
	}
	for _, p := range verifiedFixedDirectGEKO {
		n10AllowRange(m, "GEKO.EXN", p.UpperOffset, p.UpperOffset+4)
		n10AllowRange(m, "GEKO.EXN", p.LowerOffset, p.LowerOffset+4)
	}
	for _, a := range []int{0xf47c, 0xf480} {
		n10AllowRange(m, "GEKO.EXN", a, a+4)
	}
	for k, v := range m {
		sort.Slice(v, func(i, j int) bool { return v[i].Start < v[j].Start })
		merged := make([]N10DiffRange, 0, len(v))
		for _, r := range v {
			if len(merged) > 0 && r.Start <= merged[len(merged)-1].EndExclusive {
				if r.EndExclusive > merged[len(merged)-1].EndExclusive {
					merged[len(merged)-1].EndExclusive = r.EndExclusive
				}
			} else {
				merged = append(merged, r)
			}
		}
		m[k] = merged
	}
	return m
}

func n10CheckDiff(name string, before, after []byte, ranges []N10DiffRange) (N10ImageDiff, error) {
	if len(before) != len(after) {
		return N10ImageDiff{}, fmt.Errorf("%s image length changed", name)
	}
	out := N10ImageDiff{Name: name, InputSHA256: fmt.Sprintf("%x", sha256.Sum256(before)), OutputSHA256: fmt.Sprintf("%x", sha256.Sum256(after)), AllowedRanges: ranges}
	j := 0
	for i := range before {
		if before[i] == after[i] {
			continue
		}
		out.ChangedBytes++
		for j < len(ranges) && ranges[j].EndExclusive <= i {
			j++
		}
		if j >= len(ranges) || i < ranges[j].Start || i >= ranges[j].EndExclusive {
			return N10ImageDiff{}, fmt.Errorf("%s out-of-scope mutation at file offset %#x", name, i)
		}
	}
	return out, nil
}

// ComposeN10Phase2Offline atomically composes name-table relocation's stages on cloned input
// byte slices and checks their combined diff footprint.  It returns only
// host-memory copies and NEVER writes an image or asserts boot authorization.
func ComposeN10Phase2Offline(input N10OfflineTransaction) (map[string][]byte, N10OfflineTransactionReport, error) {
	fail := func(stage string, e error) (map[string][]byte, N10OfflineTransactionReport, error) {
		return nil, N10OfflineTransactionReport{}, fmt.Errorf("N10 offline transaction %s: %w", stage, e)
	}
	if sha256.Sum256(input.StagedEXE) != input.StagedEXESHA {
		return fail("revision", fmt.Errorf("staged EXE digest changed"))
	}
	if input.GEKOG2Policy != N10GEKOBare && input.GEKOG2Policy != N10GEKOSan {
		return fail("policy", fmt.Errorf("GEKO G2 requires explicit bare or san"))
	}
	if len(input.CurrentShort) != Entries || len(input.TargetShort) != Entries || len(input.TargetFull) != Entries {
		return fail("names", fmt.Errorf("expected exactly 16 current short, target short, and full names"))
	}
	if len(input.Originals) != 4 {
		return fail("originals", fmt.Errorf("requires four authenticated originals"))
	}
	for name, hash := range n10Phase2ImageSHA {
		b, exists := input.Originals[name]
		if !exists || fmt.Sprintf("%x", sha256.Sum256(b)) != hash {
			return fail("originals", fmt.Errorf("%s original digest mismatch", name))
		}
	}
	// parser-copy contract pins ALL parser string-copy/concat callsites to the authenticated
	// retail EXE. It deliberately does not assert a runtime guard or make the
	// output runnable. Unknown parser source revisions fail the transaction.
	parserContract, err := InspectN10ParserContract(input.Originals[EXE])
	if err != nil {
		return fail("parser contract", err)
	}
	if parserContract.SafeToPatch || parserContract.RuntimeGuardImplemented {
		return fail("parser contract", fmt.Errorf("unexpected parser boot authorization"))
	}
	if err := CheckStagedN10ParserPreimage(input.Originals[EXE], input.StagedEXE, parserContract); err != nil {
		return fail("parser staged preimage", err)
	}
	staged, short, err := StageInRendererPool(input.StagedEXE, input.CurrentShort, input.TargetShort)
	if err != nil {
		return fail("short", err)
	}
	if short.NewBytes <= 0 || short.NewBytes > 132 || short.PointerCount != Entries {
		return fail("short", fmt.Errorf("unexpected short layout"))
	}
	staged, full, err := StageFullNameSplit(staged, sha256.Sum256(staged), input.TargetFull)
	if err != nil {
		return fail("full", err)
	}
	if full.FirstBytes <= 0 || full.FirstBytes > 184 || full.SecondBytes <= 0 || full.SecondBytes > 44 || full.PointerWords != Entries {
		return fail("full", fmt.Errorf("unexpected full layout"))
	}
	aliasedEXE, aliasedGEKO, aliases, err := StageDirectFixedAliases(staged, input.Originals["GEKO.EXN"], input.TargetShort)
	if err != nil {
		return fail("aliases", err)
	}
	if aliases.EXEDirectRewrites != 3 || aliases.EXEInheritedRewrites != 1 || aliases.GEKODirectRewrites != 1 {
		return fail("aliases", fmt.Errorf("incomplete alias sites"))
	}
	stagedImages := map[string][]byte{EXE: aliasedEXE, "GEKO.EXN": aliasedGEKO, "SHUGAKU.EXN": input.Originals["SHUGAKU.EXN"], "SHOUGATU.EXN": input.Originals["SHOUGATU.EXN"]}
	stagedImages, ab, err := StagePhase2AB(input.Originals, stagedImages)
	if err != nil {
		return fail("buffers", err)
	}
	if ab.RewrittenA != 16 || ab.RewrittenB != 12 {
		return fail("buffers", fmt.Errorf("incomplete 16+12 address pairs"))
	}
	finalEXE, finalGEKO, g2, err := StageGEKOG2(stagedImages[EXE], stagedImages["GEKO.EXN"], input.Originals["GEKO.EXN"], input.GEKOG2Policy, input.TargetShort[11])
	if err != nil {
		return fail("GEKO G2", err)
	}
	stagedImages[EXE], stagedImages["GEKO.EXN"] = finalEXE, finalGEKO
	if g2.Policy != input.GEKOG2Policy || !g2.UnsafeToBoot {
		return fail("GEKO G2", fmt.Errorf("unexpected policy or safety status"))
	}
	// glyph-layout validation: validate actual staged pair-glyph bytes and alias pointers.
	// The 10-cell {G} budget is a validator estimate, NOT measured UI width.
	presentation, err := AuditN10Presentation(stagedImages, input.TargetShort, input.TargetFull, input.GEKOG2Policy)
	if err != nil {
		return fail("presentation", err)
	}
	allowed := n10Phase2AllowedDiffs()
	report := N10OfflineTransactionReport{ShortBytes: short.NewBytes, FullFirstBytes: full.FirstBytes, FullSecondBytes: full.SecondBytes, RewrittenA: ab.RewrittenA, RewrittenB: ab.RewrittenB, AliasSources: aliases.EXEDirectRewrites + aliases.EXEInheritedRewrites + aliases.GEKODirectRewrites, GEKOG2Policy: input.GEKOG2Policy, ParserCalls: len(parserContract.Sites), Presentation: presentation}
	for _, name := range []string{EXE, "GEKO.EXN", "SHUGAKU.EXN", "SHOUGATU.EXN"} {
		before := input.Originals[name]
		if name == EXE {
			before = input.StagedEXE
		}
		diff, err := n10CheckDiff(name, before, stagedImages[name], allowed[name])
		if err != nil {
			return fail("byte scope", err)
		}
		report.Diffs = append(report.Diffs, diff)
	}
	// In particular, no stage may modify caller-provided buffers.
	if bytes.Equal(stagedImages[EXE], input.StagedEXE) {
		return fail("diff", fmt.Errorf("EXE unexpectedly unchanged"))
	}
	return stagedImages, report, nil
}
