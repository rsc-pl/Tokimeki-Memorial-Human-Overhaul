package n20arch

// Offline prototype: suffix-free dynamic surname+given token inside an
// arbitrary mixed CP932/ASCII line (the phone form). The caller must own the
// source and destination and provide a writable capacity; the routine cannot
// be installed into C10's exhausted resident body until physical placement is
// proved. This code never rewrites either saved kana field or the source line.
//
// a0=source line (NUL within 64 B), a1=destination, a2=capacity;
// v0=output size including NUL, or 0 without modifying destination.
// All s-registers, ra, sp are preserved. Real MIPS-I load delays are explicit.
import "fmt"

func BuildC10LineFullnamePrototype(romanizer uint32) ([]byte, error) {
	a := &miniAsm{labels: map[string]int{}}
	w := func(x uint32) { a.w(x) }
	add := func(d, s uint32, i int16) { w(olADDIU(d, s, i)) }
	mov := func(d, s uint32) { w(olAddu(d, s, 0)) }
	addu := func(d, x, y uint32) { w(olAddu(d, x, y)) }
	sw := func(d uint32, o int16) { w(olSW(d, 29, o)) }
	lw := func(d uint32, o int16) { w(olLW(d, 29, o)); w(0) }
	lbu := func(d, b uint32, o int16) { w(olLBU(d, b, o)); w(0) }
	sb := func(d, b uint32, o int16) { w(olSB(d, b, o)) }
	beq := func(x, y uint32, l string) { a.b(4, x, y, l); w(0) }
	bne := func(x, y uint32, l string) { a.b(5, x, y, l); w(0) }
	jump := func(l string) { beq(0, 0, l) }
	sltu := func(d, x, y uint32) { w(olRType(x, y, d, 0x2b)) }
	// 0x20..0x8f: 112-byte atomic staging output
	// 0x90..0x9f: first romanized field; 0xa0..0xaf: second
	// 0xb0..0xcf: saved s0..s7; 0xd0: ra
	// 0xd4: surname kana bytes; 0xd8: given bytes; 0xdc: token length
	// 0xe0..0xef: original surname+given kana token (up to 12 B)
	// 0xf0: source cursor; 0xf4: resulting output length
	add(29, 29, -0x130)
	for i, r := range []uint32{16, 17, 18, 19, 20, 21, 22, 23} {
		sw(r, int16(0xb0+i*4))
	}
	sw(31, 0xd0)
	mov(16, 4)
	mov(17, 5)
	mov(18, 6)
	beq(16, 0, "fail")
	beq(17, 0, "fail")
	w(olSLTIU(8, 18, 32))
	bne(8, 0, "fail")
	// Count and copy CP932 surname to private needle buffer. Each field 1..3 kana.
	w(olLUI(19, OLA0SurnameField))
	w(olORI(19, 19, OLA0SurnameField&0xffff))
	add(21, 0, 0)
	a.label("surname_loop")
	w(olSLTIU(8, 21, 7))
	beq(8, 0, "fail")
	addu(9, 19, 21)
	lbu(10, 9, 0)
	beq(10, 0, "surname_end")
	addu(9, 29, 21)
	sb(10, 9, 0xe0)
	add(21, 21, 1)
	jump("surname_loop")
	a.label("surname_end")
	beq(21, 0, "fail")
	w(olIType(12, 21, 8, 1))
	bne(8, 0, "fail")
	sw(21, 0xd4)
	// Complete token with 1..3 given-name kana.
	w(olLUI(20, OLFieldPrepSavedGiv))
	w(olORI(20, 20, OLFieldPrepSavedGiv&0xffff))
	add(22, 0, 0)
	a.label("given_loop")
	w(olSLTIU(8, 22, 7))
	beq(8, 0, "fail")
	addu(9, 20, 22)
	lbu(10, 9, 0)
	beq(10, 0, "given_end")
	addu(9, 21, 22)
	addu(9, 29, 9)
	sb(10, 9, 0xe0)
	add(22, 22, 1)
	jump("given_loop")
	a.label("given_end")
	beq(22, 0, "fail")
	w(olIType(12, 22, 8, 1))
	bne(8, 0, "fail")
	sw(22, 0xd8)
	addu(23, 21, 22)
	sw(23, 0xdc)
	// Find NUL within 64 bytes, irrespective of ASCII/CP932 prefix parity.
	add(22, 0, 0)
	a.label("source_len")
	w(olSLTIU(8, 22, 64))
	beq(8, 0, "fail")
	addu(9, 16, 22)
	lbu(10, 9, 0)
	beq(10, 0, "source_done")
	add(22, 22, 1)
	jump("source_len")
	a.label("source_done")
	sltu(8, 22, 23)
	bne(8, 0, "fail")
	// Scan only CP932 character boundaries; refuse more than one occurrence.
	add(21, 0, 0)
	add(19, 0, -1)
	a.label("find")
	addu(9, 21, 23)
	sltu(8, 22, 9)
	bne(8, 0, "find_end")
	add(11, 0, 0)
	a.label("match")
	beq(11, 23, "record")
	addu(9, 29, 11)
	lbu(10, 9, 0xe0)
	addu(9, 16, 21)
	addu(9, 9, 11)
	lbu(12, 9, 0)
	bne(10, 12, "advance")
	add(11, 11, 1)
	jump("match")
	a.label("record")
	add(8, 0, -1)
	bne(19, 8, "fail")
	mov(19, 21)
	a.label("advance")
	addu(9, 16, 21)
	lbu(10, 9, 0)
	w(olSLTIU(8, 10, 0x81))
	bne(8, 0, "one")
	w(olSLTIU(8, 10, 0xa0))
	bne(8, 0, "two")
	w(olSLTIU(8, 10, 0xe0))
	bne(8, 0, "one")
	w(olSLTIU(8, 10, 0xfd))
	bne(8, 0, "two")
	a.label("one")
	add(21, 21, 1)
	jump("find")
	a.label("two")
	add(21, 21, 2)
	jump("find")
	a.label("find_end")
	add(8, 0, -1)
	beq(19, 8, "fail")
	// Independently romanize surname/given (never reinterpret saved source data).
	w(olLUI(4, OLA0SurnameField))
	w(olORI(4, 4, OLA0SurnameField&0xffff))
	add(5, 29, 0x90)
	add(6, 0, 16)
	add(7, 0, 3)
	w(jalWord(romanizer))
	w(0)
	beq(2, 0, "fail")
	w(olSLTIU(8, 2, 17))
	beq(8, 0, "fail")
	w(olLUI(4, OLFieldPrepSavedGiv))
	w(olORI(4, 4, OLFieldPrepSavedGiv&0xffff))
	add(5, 29, 0xa0)
	add(6, 0, 16)
	add(7, 0, 3)
	w(jalWord(romanizer))
	w(0)
	beq(2, 0, "fail")
	w(olSLTIU(8, 2, 17))
	beq(8, 0, "fail")
	// First field to staging after source prefix.
	add(11, 0, 0)
	a.label("prefix")
	beq(11, 19, "surname_roman")
	addu(9, 16, 11)
	lbu(10, 9, 0)
	addu(9, 29, 11)
	sb(10, 9, 0x20)
	add(11, 11, 1)
	jump("prefix")
	a.label("surname_roman")
	add(12, 0, 0)
	a.label("surname_roman_loop")
	addu(9, 29, 12)
	lbu(10, 9, 0x90)
	beq(10, 0, "surname_join")
	addu(9, 11, 12)
	addu(9, 29, 9)
	sb(10, 9, 0x20)
	add(12, 12, 1)
	jump("surname_roman_loop")
	a.label("surname_join")
	addu(11, 11, 12)
	// Delete a trailing high-bit pad if romanizer emitted it.
	add(9, 11, -1)
	addu(9, 29, 9)
	lbu(10, 9, 0x20)
	add(8, 0, 0xa0)
	bne(10, 8, "separator")
	add(11, 11, -1)
	a.label("separator")
	addu(9, 29, 11)
	add(10, 0, 0xa0)
	sb(10, 9, 0x20)
	add(11, 11, 1)
	add(12, 0, 0)
	a.label("given_roman_loop")
	addu(9, 29, 12)
	lbu(10, 9, 0xa0)
	beq(10, 0, "given_done")
	addu(9, 11, 12)
	addu(9, 29, 9)
	sb(10, 9, 0x20)
	add(12, 12, 1)
	jump("given_roman_loop")
	a.label("given_done")
	addu(11, 11, 12)
	// Compute tail bytes, including NUL. Commit only after complete fit check.
	addu(10, 19, 23) // consumed prefix + original 2-field token
	sltu(8, 22, 10)
	bne(8, 0, "fail")
	w(olSUBU(12, 22, 10))
	addu(14, 11, 12)
	add(14, 14, 1)
	sltu(8, 18, 14)
	bne(8, 0, "fail")
	w(olSLTIU(8, 14, 113))
	beq(8, 0, "fail")
	a.label("tail")
	addu(9, 16, 10)
	lbu(12, 9, 0)
	addu(9, 29, 11)
	sb(12, 9, 0x20)
	add(10, 10, 1)
	add(11, 11, 1)
	sltu(8, 22, 10)
	beq(8, 0, "tail")
	add(8, 0, 0)
	a.label("commit")
	beq(8, 14, "success")
	addu(9, 29, 8)
	lbu(10, 9, 0x20)
	addu(9, 17, 8)
	sb(10, 9, 0)
	add(8, 8, 1)
	jump("commit")
	a.label("success")
	mov(2, 14)
	jump("exit")
	a.label("fail")
	mov(2, 0)
	a.label("exit")
	for i, r := range []uint32{16, 17, 18, 19, 20, 21, 22, 23} {
		lw(r, int16(0xb0+i*4))
	}
	lw(31, 0xd0)
	w(olJR(31))
	add(29, 29, 0x130)
	a.resolve()
	b := words(a.words...)
	if len(b) > 2048 {
		return nil, fmt.Errorf("prototype unexpected growth: %d B", len(b))
	}
	return b, nil
}
