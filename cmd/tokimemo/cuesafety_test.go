func TestNativeCueAuditAcceptsTwoSeparateTracks(t *testing.T) {
	root := t.TempDir()
	if err := os.Mkdir(filepath.Join(root, "sub"), 0700); err != nil {
		t.Fatal(err)
	}
	for _, p := range []string{"track one.bin", "sub/track two.bin"} {
		if err := os.WriteFile(filepath.Join(root, p), bytes.Repeat([]byte{1}, 2352*2), 0600); err != nil {
			t.Fatal(err)
		}
	}
	cue := filepath.Join(root, "game.cue")
	data := "REM Generated by test\r\nFILE \"track one.bin\" BINARY\r\n TRACK 01 MODE2/2352\r\n INDEX 01 00:00:00\r\nFILE \"sub/track two.bin\" BINARY\r\n TRACK 02 AUDIO\r\n INDEX 01 00:00:00\r\n"
	if err := os.WriteFile(cue, []byte(data), 0600); err != nil {
		t.Fatal(err)
	}
	audit, err := auditCueForNative(cue)
	if err != nil || audit.Tracks != 2 || audit.InputFiles != 2 || audit.DataSectors != 2 || audit.AudioSectors != 2 {
		t.Fatalf("audit=%+v err=%v", audit, err)
	}
	stage := filepath.Join(t.TempDir(), "staged")
	if err := os.Mkdir(stage, 0700); err != nil {
		t.Fatal(err)
	}
	info, err := parseCue(cue)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := stageCue(cue, info, stage); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(stage, "game.cue"))
	if err != nil || !bytes.Equal(got, []byte(data)) {
		t.Fatal("cue staging changed original CUE")
	}
}

func TestNativeCueAuditOriginalPlayStationTheBestAudioIndex00(t *testing.T) {
	dir := t.TempDir()
	for _, item := range []struct {
		name    string
		sectors int
	}{{"track1.bin", 20}, {"track2.bin", 151}} {
		if err := os.WriteFile(filepath.Join(dir, item.name), bytes.Repeat([]byte{1}, 2352*item.sectors), 0600); err != nil {
			t.Fatal(err)
		}
	}
	cue := filepath.Join(dir, "original.cue")
	text := "FILE \"track1.bin\" BINARY\n  TRACK 01 MODE2/2352\n    FLAGS DCP\n    INDEX 01 00:00:00\nFILE \"track2.bin\" BINARY\n  TRACK 02 AUDIO\n    FLAGS DCP\n    INDEX 00 00:00:00\n    INDEX 01 00:02:00\n"
	if err := os.WriteFile(cue, []byte(text), 0600); err != nil {
		t.Fatal(err)
	}
	a, err := auditCueForNative(cue)
	if err != nil || a.AudioPregapSectors != 150 || a.AudioSectors != 151 {
		t.Fatalf("audit=%+v: %v", a, err)
	}
	info, err := parseCue(cue)
	if err != nil {
		t.Fatal(err)
	}
	stage := filepath.Join(dir, "stage")
	if err := os.Mkdir(stage, 0700); err != nil {
		t.Fatal(err)
	}
	if _, err := stageCue(cue, info, stage); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(stage, "original.cue"))
	if err != nil || !bytes.Equal(got, []byte(text)) {
		t.Fatalf("CUE changed: %v", err)
	}
	for _, file := range []string{"track1.bin", "track2.bin"} {
		original, err := os.ReadFile(filepath.Join(dir, file))
		if err != nil {
			t.Fatal(err)
		}
		copyBytes, err := os.ReadFile(filepath.Join(stage, file))
		if err != nil || !bytes.Equal(original, copyBytes) {
			t.Fatalf("track changed %s: %v", file, err)
		}
	}
}

func TestNativeCueAuditRejectsUnsafeLayouts(t *testing.T) {
	base := "FILE \"one.bin\" BINARY\n TRACK 01 MODE2/2352\n INDEX 01 00:00:00\nFILE \"two.bin\" BINARY\n TRACK 02 AUDIO\n INDEX 01 00:00:00\n"
	invalid := map[string]string{
		"nonzero index":         strings.Replace(base, "INDEX 01 00:00:00", "INDEX 01 00:02:00", 1),
		"index 00 on data":      strings.Replace(base, "INDEX 01 00:00:00", "INDEX 00 00:00:00\n INDEX 01 00:00:00", 1),
		"pregap":                strings.Replace(base, " TRACK 02 AUDIO", " TRACK 02 AUDIO\n PREGAP 00:02:00", 1),
		"single file":           "FILE \"one.bin\" BINARY\n TRACK 01 MODE2/2352\n INDEX 01 00:00:00\n TRACK 02 AUDIO\n INDEX 01 00:00:00\n",
		"duplicate file":        strings.Replace(base, "two.bin", "one.bin", 1),
		"extra track":           base + "FILE \"three.bin\" BINARY\n TRACK 03 AUDIO\n INDEX 01 00:00:00\n",
		"missing index":         strings.Replace(base, " INDEX 01 00:00:00\n", "", 1),
		"absolute":              strings.Replace(base, "one.bin", "/tmp/one.bin", 1),
		"parent escape":         strings.Replace(base, "one.bin", "../one.bin", 1),
		"wrong format":          strings.Replace(base, "MODE2/2352", "MODE1/2352", 1),
		"wave":                  strings.Replace(base, "BINARY", "WAVE", 1),
		"unrecognized":          base + "UNKNOWN 42\n",
		"index 00 without 150":  strings.Replace(base, " TRACK 02 AUDIO\n INDEX 01 00:00:00", " TRACK 02 AUDIO\n INDEX 00 00:00:00\n INDEX 01 00:00:00", 1),
		"index 01 offset no 00": strings.Replace(base, "TRACK 02 AUDIO\n INDEX 01 00:00:00", "TRACK 02 AUDIO\n INDEX 01 00:02:00", 1),
		"malformed file":        strings.Replace(base, "BINARY", "BINARY GARBAGE", 1),
	}
	for name, body := range invalid {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			for _, f := range []string{"one.bin", "two.bin", "three.bin"} {
				if err := os.WriteFile(filepath.Join(dir, f), bytes.Repeat([]byte{1}, 2352*2), 0600); err != nil {
					t.Fatal(err)
				}
			}
			cue := filepath.Join(dir, "game.cue")
			if err := os.WriteFile(cue, []byte(body), 0600); err != nil {
				t.Fatal(err)
			}
			if _, err := auditCueForNative(cue); err == nil {
				t.Fatalf("unsafe case accepted: %s", name)
			}
		})
	}
}

func TestNativeCueAuditRejectsLinksAndPartialSectors(t *testing.T) {
	dir := t.TempDir()
	other := t.TempDir()
	track := filepath.Join(other, "target.bin")
	if err := os.WriteFile(track, bytes.Repeat([]byte{1}, 2352*2), 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(track, filepath.Join(dir, "one.bin")); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "two.bin"), bytes.Repeat([]byte{1}, 2352*2), 0600); err != nil {
		t.Fatal(err)
	}
	cue := filepath.Join(dir, "game.cue")
	body := "FILE one.bin BINARY\nTRACK 01 MODE2/2352\nINDEX 01 00:00:00\nFILE two.bin BINARY\nTRACK 02 AUDIO\nINDEX 01 00:00:00\n"
	if err := os.WriteFile(cue, []byte(body), 0600); err != nil {
		t.Fatal(err)
	}
	if _, err := auditCueForNative(cue); err == nil {
		t.Fatal("followed source symlink")
	}
	if err := os.Remove(filepath.Join(dir, "one.bin")); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "one.bin"), []byte{1}, 0600); err != nil {
		t.Fatal(err)
	}
	if _, err := auditCueForNative(cue); err == nil {
		t.Fatal("accepted partial sector")
	}
	if err := os.WriteFile(filepath.Join(dir, "one.bin"), bytes.Repeat([]byte{1}, 2352*2), 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(cue, filepath.Join(dir, "linked.cue")); err != nil {
		t.Fatal(err)
	}
	if _, err := auditCueForNative(filepath.Join(dir, "linked.cue")); err == nil {
		t.Fatal("followed source cue symlink")
	}
}

func TestPublishNativeDirectoryNoReplace(t *testing.T) {
	if runtime.GOOS != "linux" {
		t.Skip("Linux atomic no-replace publish")
	}
	parent := t.TempDir()
	stage := filepath.Join(parent, "stage")
	if err := os.Mkdir(stage, 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(stage, "proof"), []byte("native"), 0600); err != nil {
		t.Fatal(err)
	}
	dest := filepath.Join(parent, "dest")
	if err := os.Mkdir(dest, 0700); err != nil {
		t.Fatal(err)
	}
	if err := publishNativeDirectory(stage, dest); err == nil {
		t.Fatal("replaced existing empty dir")
	}
	if _, err := os.Stat(filepath.Join(stage, "proof")); err != nil {
		t.Fatal("lost stage on refused publish")
	}
	if err := os.Remove(dest); err != nil {
		t.Fatal(err)
	}
	if err := publishNativeDirectory(stage, dest); err != nil {
		t.Fatal(err)
	}
	raw, err := os.ReadFile(filepath.Join(dest, "proof"))
	if err != nil || string(raw) != "native" {
		t.Fatal("not published")
	}
}
