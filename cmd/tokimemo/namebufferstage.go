package main

import (
	"crypto/sha256"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"tokimemo/internal/nametables"
)

// This deliberately produces research files, not a playable image. It never
// changes the default build or any translation. It consumes name-stage's
// attested candidate EXE and the owner's original GEKO.EXN directly from ISO.
func cmdNameBufferStage(root string, args []string) error {
	fs := flag.NewFlagSet("name-buffer-stage", flag.ContinueOnError)
	fs.SetOutput(commandOutput)
	candidate := fs.String("candidate-exe", "", "EXE previously generated by name-stage")
	prefix := fs.String("output-prefix", "", "private prefix for EXE/GEKO/JSON candidates")
	game := fs.String("game", "", "original two-track CUE (auto-discover if omitted)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if fs.NArg() != 0 || *candidate == "" || *prefix == "" {
		return errors.New("usage: tokimemo name-buffer-stage --candidate-exe .local/go_toolchain/checkpoints/N10.EXE --output-prefix .local/go_toolchain/checkpoints/N10_AB [--game ORIGINAL.cue]")
	}
	private, err := filepath.Abs(filepath.Join(root, ".local", "go_toolchain"))
	if err != nil {
		return err
	}
	for _, path := range []string{*candidate, *prefix} {
		abs, e := filepath.Abs(path)
		if e != nil {
			return e
		}
		rel, e := filepath.Rel(private, abs)
		if e != nil || rel == "." || rel == ".." || strings.HasPrefix(rel, ".."+string(os.PathSeparator)) {
			return fmt.Errorf("path must be inside private Go workspace: %s", path)
		}
		// Existing parent directories are resolved and checked to prevent symlink escapes.
		parent := filepath.Dir(abs)
		if e = os.MkdirAll(parent, 0700); e != nil {
			return e
		}
		resolved, e := filepath.EvalSymlinks(parent)
		if e != nil {
			return e
		}
		realRoot, e := filepath.EvalSymlinks(private)
		if e != nil {
			return e
		}
		rel, e = filepath.Rel(realRoot, resolved)
		if e != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(os.PathSeparator)) {
			return fmt.Errorf("symlink escape in path: %s", path)
		}
	}
	input, err := os.ReadFile(*candidate)
	if err != nil {
		return err
	}
	// Only a G14+ name-stage candidate, with a matching provenance report, can
	// be used. This does not attest to game boot or buffer lifetimes.
	manifest, err := os.ReadFile(*candidate + ".json")
	if err != nil {
		return fmt.Errorf("name-stage provenance missing: %w", err)
	}
	var previous struct {
		Status                 string                      `json:"status"`
		CandidateHash          string                      `json:"candidate_sha256"`
		CompactEntries         int                         `json:"compact_entries"`
		CompleteCallerCoverage bool                        `json:"complete_caller_coverage"`
		Result                 nametables.RelocationResult `json:"relocation"`
	}
	if err = json.Unmarshal(manifest, &previous); err != nil {
		return err
	}
	if previous.Status != "EXPERIMENTAL_EXE_ONLY_NOT_BOOT_APPROVED" || previous.CompactEntries != 16 || previous.Result.NewBytes != 132 || previous.CompleteCallerCoverage || previous.CandidateHash != fmt.Sprintf("%x", sha256.Sum256(input)) {
		return errors.New("invalid name-stage provenance; expected verified 132-byte N10 candidate")
	}
	cue, err := cueChoice(root, *game)
	if err != nil {
		return err
	}
	tracks, err := parseCue(cue)
	if err != nil {
		return err
	}
	f, iso, err := openDiscISO(tracks.Data, tracks.Sectors)
	if err != nil {
		return err
	}
	defer f.Close()
	origGEKO, err := (isoSource{iso}).ReadFile(nametables.Geko)
	if err != nil {
		return err
	}
	exe, geko, summary, err := nametables.StageABResearchCandidates(input, origGEKO)
	if err != nil {
		return err
	}
	// All three exclusive creations are rolled back if any one fails. Never
	// touch files outside the private namespace, or replace existing output.
	names := []string{*prefix + ".EXE", *prefix + ".GEKO.EXN", *prefix + ".json"}
	for _, path := range names {
		if _, e := os.Lstat(path); e == nil {
			return fmt.Errorf("output already exists: %s", path)
		} else if !os.IsNotExist(e) {
			return e
		}
	}
	raw, err := json.MarshalIndent(summary, "", "  ")
	if err != nil {
		return err
	}
	data := [][]byte{exe, geko, append(raw, '\n')}
	created := []string{}
	success := false
	defer func() {
		if !success {
			for _, path := range created {
				os.Remove(path)
			}
		}
	}()
	for i, path := range names {
		out, e := os.OpenFile(path, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
		if e != nil {
			return e
		}
		created = append(created, path)
		if _, e = out.Write(data[i]); e != nil {
			out.Close()
			return e
		}
		if e = out.Sync(); e != nil {
			out.Close()
			return e
		}
		if e = out.Close(); e != nil {
			return e
		}
	}
	success = true
	fmt.Fprintf(commandOutput, "N10 A/B *research only*: %d EXE + %d GEKO direct sites rewritten; C unchanged.\nOutputs: %s, %s, %s\nNEVER BOOT OR INSTALL THESE CANDIDATES. Indirect aliases, safe RAM lifetime, special strings and widths remain unproven.\n", summary.EXESites, summary.GEKOSites, names[0], names[1], names[2])
	return nil
}
